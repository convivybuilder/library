"""bin/lock-requirements — the script that compiles requirements.txt into
requirements.lock and checks the committed lock.

Every case runs a copy of the script in a scratch repository, with a stub
`uv` first on PATH. The stub writes a lock derived only from
requirements.txt and the --exclude-newer time it was given, so these cases
test the script's own logic offline: which arguments reach uv, that every
compile writes into an empty file, what --check compares, and the --base
rule. Whether uv resolves correctly is uv's concern, and CI's own
`bin/lock-requirements --check` step runs the real one.

The stub refuses to write into an output file that already has content.
uv treats an existing output file as version preferences, and round 1 of
this script compiled --check into a copy of the committed lock, which let a
hand-edited lock reproduce itself and pass (library PR 315)."""
import hashlib
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "bin" / "lock-requirements"

AS_OF = "2026-10-24T00:44:52Z"
EARLIER = "2026-10-23T00:44:52Z"
LATER = "2026-10-25T00:44:52Z"

STUB_UV = """#!{python}
import hashlib, sys
from pathlib import Path

args = sys.argv[1:]
if args[:2] != ["pip", "compile"]:
    sys.exit("stub uv: unexpected command " + " ".join(args))
opts = {{}}
i = 2
while i < len(args):
    if args[i] in ("--exclude-newer", "--custom-compile-command", "-o", "--python-version"):
        opts[args[i]] = args[i + 1]
        i += 2
    else:
        opts[args[i]] = True
        i += 1
for flag in ("--universal", "--generate-hashes"):
    if flag not in opts:
        sys.exit("stub uv: missing " + flag)
out = Path(opts["-o"])
if out.exists() and out.read_text():
    sys.exit("stub uv: output file already has content, which uv would read as preferences")
pins = [line.split("#")[0].strip() for line in Path("requirements.txt").read_text().splitlines()]
body = "".join(
    "{{}} \\\\\\n    --hash=sha256:{{}}\\n".format(
        pin, hashlib.sha256((pin + opts["--exclude-newer"]).encode()).hexdigest())
    for pin in pins if pin)
out.write_text(
    "# This file was autogenerated by uv via the following command:\\n"
    "#    " + opts["--custom-compile-command"] + "\\n" + body)
"""


def _git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True, text=True)


@pytest.fixture
def repo(tmp_path):
    root = tmp_path / "repo"
    (root / "bin").mkdir(parents=True)
    shutil.copy2(SCRIPT, root / "bin" / "lock-requirements")
    (root / "requirements.txt").write_text("# a comment\nalpha==1.0\nbeta==2.0\n")
    stub_dir = tmp_path / "stub"
    stub_dir.mkdir()
    stub = stub_dir / "uv"
    stub.write_text(STUB_UV.format(python=sys.executable))
    stub.chmod(0o755)
    _git(root, "init", "-q", "-b", "main")
    _git(root, "config", "user.email", "test@example.invalid")
    _git(root, "config", "user.name", "test")
    return root


def run(repo, *args):
    stub_dir = repo.parent / "stub"
    env = {"PATH": f"{stub_dir}:/usr/bin:/bin", "HOME": str(repo.parent)}
    return subprocess.run([str(repo / "bin" / "lock-requirements"), *args], cwd=repo,
                          env=env, capture_output=True, text=True, check=False)


def commit(repo, message="commit"):
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", message)
    return _git(repo, "rev-parse", "HEAD").stdout.strip()


def lock(repo):
    return (repo / "requirements.lock").read_text()


def test_regenerating_records_the_as_of_time_and_check_passes(repo):
    result = run(repo, "--as-of", AS_OF)
    assert result.returncode == 0, result.stderr
    assert lock(repo).splitlines()[1] == f"#    bin/lock-requirements --as-of {AS_OF}"
    assert "alpha==1.0" in lock(repo)

    check = run(repo, "--check")
    assert check.returncode == 0, check.stderr
    assert f"as of {AS_OF}" in check.stdout


def test_regenerating_with_no_argument_stamps_a_time_check_can_read(repo):
    assert run(repo).returncode == 0
    assert run(repo, "--check").returncode == 0


def test_check_compiles_into_an_empty_file_and_rejects_a_hand_edited_lock(repo):
    assert run(repo, "--as-of", AS_OF).returncode == 0
    edited = lock(repo).replace("beta==2.0", "beta==1.9")
    (repo / "requirements.lock").write_text(edited)

    check = run(repo, "--check")
    assert check.returncode == 1, check.stdout + check.stderr
    assert "already has content" not in check.stderr
    assert "is not what requirements.txt resolves to" in check.stderr


def test_check_fails_after_a_pin_moves_in_requirements_txt(repo):
    assert run(repo, "--as-of", AS_OF).returncode == 0
    (repo / "requirements.txt").write_text("alpha==1.1\nbeta==2.0\n")
    assert run(repo, "--check").returncode == 1


@pytest.mark.parametrize("header", [
    "#    bin/lock-requirements --as-of 2026-10-24",
    "#    bin/lock-requirements --as-of yesterday",
    "#    bin/lock-requirements",
])
def test_check_fails_on_a_header_with_no_readable_as_of(repo, header):
    assert run(repo, "--as-of", AS_OF).returncode == 0
    lines = lock(repo).splitlines(keepends=True)
    lines[1] = header + "\n"
    (repo / "requirements.lock").write_text("".join(lines))

    check = run(repo, "--check")
    assert check.returncode == 1
    assert "records no --as-of time" in check.stderr


@pytest.mark.parametrize("args", [
    ("--as-of", "yesterday"), ("--as-of",), ("--check", "--bogus"), ("--check", "--base"),
    ("--bogus",),
])
def test_bad_arguments_are_usage_errors(repo, args):
    assert run(repo, "--as-of", AS_OF).returncode == 0
    assert run(repo, *args).returncode == 2


def test_base_with_the_same_or_an_earlier_as_of_passes(repo):
    assert run(repo, "--as-of", EARLIER).returncode == 0
    base = commit(repo, "earlier lock")
    assert run(repo, "--check", "--base", base).returncode == 0

    assert run(repo, "--as-of", LATER).returncode == 0
    check = run(repo, "--check", "--base", base)
    assert check.returncode == 0, check.stderr


def test_an_as_of_earlier_than_the_base_fails_even_though_it_recompiles(repo):
    """The round-2 finding: moving the time back and recompiling yields a
    lock --check alone reproduces."""
    assert run(repo, "--as-of", AS_OF).returncode == 0
    base = commit(repo, "lock")
    assert run(repo, "--as-of", EARLIER).returncode == 0
    assert run(repo, "--check").returncode == 0

    check = run(repo, "--check", "--base", base)
    assert check.returncode == 1
    assert f"resolves as of {EARLIER}, earlier than" in check.stderr


def test_a_base_with_no_lock_has_nothing_to_compare(repo):
    base = commit(repo, "no lock yet")
    assert run(repo, "--as-of", AS_OF).returncode == 0
    check = run(repo, "--check", "--base", base)
    assert check.returncode == 0, check.stderr
    assert "nothing to compare --as-of against" in check.stdout


def test_a_base_lock_with_an_unreadable_header_fails(repo):
    (repo / "requirements.lock").write_text("# no header here\nalpha==1.0\n")
    base = commit(repo, "bad lock")
    assert run(repo, "--as-of", AS_OF).returncode == 0
    check = run(repo, "--check", "--base", base)
    assert check.returncode == 1
    assert "an unreadable time" in check.stderr


def test_stub_hash_depends_on_the_as_of_time(repo):
    """The stub's output must change with --exclude-newer, or the --base
    cases above could pass without the script passing the time through."""
    assert run(repo, "--as-of", AS_OF).returncode == 0
    first = lock(repo)
    assert run(repo, "--as-of", LATER).returncode == 0
    expected = hashlib.sha256(("alpha==1.0" + LATER).encode()).hexdigest()
    assert expected in lock(repo)
    assert lock(repo).split("\n", 2)[2] != first.split("\n", 2)[2]
